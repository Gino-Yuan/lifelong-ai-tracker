def _fs(*present: str):
    have = {str(Path(p)) for p in present}
    return lambda p: str(p) in have


def test_find_chromium_macos_order(tmp_path):
    chrome = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
    edge = "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge"
    no_which = lambda exe: None  # noqa: E731
    b = launcher.find_chromium("macos", home=tmp_path, is_file=_fs(edge, chrome), which=no_which)
    assert b == Browser("Google Chrome", Path(chrome))
    b = launcher.find_chromium("macos", home=tmp_path, is_file=_fs(edge), which=no_which)
    assert b.name == "Microsoft Edge"
    user_brave = tmp_path / "Applications" / "Brave Browser.app/Contents/MacOS/Brave Browser"
    assert launcher.find_chromium("macos", home=tmp_path, is_file=_fs(user_brave), which=no_which).name == "Brave"
    arc = "/Applications/Arc.app/Contents/MacOS/Arc"
    assert launcher.find_chromium("macos", home=tmp_path, is_file=_fs(arc), which=no_which) == Browser("Arc", Path(arc))
    assert launcher.find_chromium("macos", home=tmp_path, is_file=_fs(), which=no_which) is None


def test_find_chromium_linux_uses_path_lookup(tmp_path):
    seen = []

    def which(exe):
        seen.append(exe)
        return {"brave-browser": "/usr/bin/brave-browser"}.get(exe)

    b = launcher.find_chromium("linux", home=tmp_path, is_file=_fs(), which=which)
    assert b == Browser("Brave", Path("/usr/bin/brave-browser"))
    assert seen[:4] == ["google-chrome", "google-chrome-stable", "microsoft-edge", "microsoft-edge-stable"]
    assert launcher.find_chromium("linux", home=tmp_path, is_file=_fs(), which=lambda e: None) is None


def test_find_chromium_windows_install_paths(tmp_path):
    edge = Path(r"C:\Program Files (x86)") / r"Microsoft\Edge\Application\msedge.exe"
    b = launcher.find_chromium("windows", home=tmp_path, is_file=_fs(edge), which=lambda e: None)
    assert b == Browser("Microsoft Edge", edge)
    user_chrome = tmp_path / "AppData" / "Local" / r"Google\Chrome\Application\chrome.exe"
    b = launcher.find_chromium("windows", home=tmp_path, is_file=_fs(user_chrome, edge), which=lambda e: None)
    assert b.name == "Google Chrome"
    b = launcher.find_chromium("windows", home=tmp_path, is_file=_fs(),
                               which=lambda e: r"C:\tools\msedge.exe" if e == "msedge" else None)
    assert b.name == "Microsoft Edge"


