def test_open_dashboard_app_window_and_fallbacks():
    launched, opened = [], []
    chrome = Browser("Google Chrome", Path("/x/chrome"))

    def web(url):
        opened.append(url)
        return True

    assert launcher.open_dashboard(URL, chrome, launch=launched.append, web_open=web) == "app:Google Chrome"
    assert launched == [[str(Path("/x/chrome")), f"--app={URL}"]] and opened == []

    def broken(cmd):
        raise FileNotFoundError(cmd[0])

    assert launcher.open_dashboard(URL, chrome, launch=broken, web_open=web) == "browser" and opened == [URL]
    assert launcher.open_dashboard(URL, None, launch=launched.append, web_open=web) == "browser"
    assert len(launched) == 1  # no app window without a browser
    assert launcher.open_dashboard(URL, None, web_open=lambda u: False) == "failed"


