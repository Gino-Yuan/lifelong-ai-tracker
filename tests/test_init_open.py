class World:
    """Stubs for everything `tracker open` would otherwise start or probe."""

    def __init__(self, monkeypatch, tmp_path):
        self.tmp = tmp_path
        self.db = tmp_path / "data" / "tracker.db"
        self.sources = tmp_path / "sources.json"
        self.up = False
        self.in_use = False
        self.runs: list[dict] = []
        self.launched: list[list[str]] = []
        self.opened: list[str] = []
        self.browser: Browser | None = None
        self.launch_error: OSError | None = None
        self.done = threading.Event()
        self.expect_open = True
        monkeypatch.setattr(launcher, "port_accepts", self._accepts)
        monkeypatch.setattr(launcher, "_popen_detached", self._launch)
        monkeypatch.setattr(launcher.webbrowser, "open", self._web)
        monkeypatch.setattr(launcher, "find_chromium", lambda platform, **kw: self.browser)
        monkeypatch.setattr("uvicorn.run", self._run)

    def _accepts(self, host, port, timeout=0.25):
        return self.in_use or self.up

    def _launch(self, cmd):
        if self.launch_error:
            raise self.launch_error
        self.launched.append(cmd)
        self.done.set()

    def _web(self, url, *a, **k):
        self.opened.append(url)
        self.done.set()
        return True

    def _run(self, app, **kw):
        self.runs.append({"app": app, **kw})
        self.up = True                       # the server is now accepting connections
        if self.expect_open:
            assert self.done.wait(5), "browser was never opened"

    def logs(self) -> Path:
        src = self.tmp / "logs"
        write(src / "p" / "s.jsonl", assistant_line("m1"), assistant_line("m2"), assistant_line("m3"))
        return src

    def config(self, *entries: dict) -> Path:
        self.sources.write_text(json.dumps({"sources": list(entries)}), encoding="utf-8")
        return self.sources

    def open(self, *args: str):
        return runner.invoke(cli.app, ["open", "--sources", str(self.sources), "--db", str(self.db),
                                       "--pricing", str(TEST_PRICING),
                                       "--subscriptions", str(self.tmp / "subscriptions.json"), *args])


