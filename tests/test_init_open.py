def test_wait_for_port_polls_until_up_or_stopped(monkeypatch):
    answers = iter([False, False, True])
    monkeypatch.setattr(launcher, "port_accepts", lambda h, p, timeout=0.25: next(answers))
    assert launcher.wait_for_port("127.0.0.1", 8765, stop=threading.Event(), interval=0) is True
    monkeypatch.setattr(launcher, "port_accepts", lambda h, p, timeout=0.25: False)
    stop = threading.Event()
    stop.set()
    assert launcher.wait_for_port("127.0.0.1", 8765, stop=stop) is False
    assert launcher.wait_for_port("127.0.0.1", 8765, stop=threading.Event(), timeout=0.05, interval=0.01) is False


