"""`tracker init` (sources.json wizard) and `tracker open` (sync + serve + browser window).

Terminal input comes from CliRunner, `uvicorn.run` is replaced by a fake, and no
browser or other process is ever started: the app-window launcher,
`webbrowser.open`, the port probe and browser detection are all stubbed. The
wizard never looks at the tools' folders, so no home-directory path is touched.
"""

