"""`tracker init`: build sources.json from a few questions.

The wizard only writes a config file. It never opens, lists or checks the tools'
log folders (paths are validated later by `tracker sync-all` / `tracker open`),
so running it - or its tests - touches nothing outside the chosen output file.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from lifelong_tracker import fsutil
from lifelong_tracker.sources import BILLING_MODES, BILLING_SUBSCRIPTION

# (tool, default path written to sources.json); `~` is expanded when the config is loaded
_DEFAULTS: tuple[tuple[str, str], ...] = (
    ("claude-code", "~/.claude/projects"),
    ("antigravity", "~/.gemini/antigravity/brain"),
    ("codex", "~/.codex/state_5.sqlite"),
    ("opencode", "~/.local/share/opencode/opencode.db"),
)
_WINDOWS_OPENCODE = "~/AppData/Local/opencode/opencode.db"  # = %LOCALAPPDATA%\opencode\opencode.db
_LOCALAPPDATA_RE = re.compile(r"^%LOCALAPPDATA%(?=[\\/]|$)", re.I)
_HOME_RE = re.compile(r"^%USERPROFILE%(?=[\\/]|$)", re.I)


@dataclass(frozen=True)
class ToolDefault:
    tool: str
    path: str   # written to sources.json
    hint: str   # shown to the user (the OS's usual spelling)


@dataclass(frozen=True)
class Choice:
    tool: str
    enabled: bool
    path: str
    billing: str = BILLING_SUBSCRIPTION


def tool_defaults(platform: str) -> list[ToolDefault]:
    """Default location of each tool's usage data on `platform` (macos / linux / windows)."""
    out = []
    for tool, path in _DEFAULTS:
        hint = path
        if platform == "windows":
            if tool == "opencode":
                path, hint = _WINDOWS_OPENCODE, r"%LOCALAPPDATA%\opencode\opencode.db"
            else:
                hint = "%USERPROFILE%\\" + path[2:].replace("/", "\\")
        out.append(ToolDefault(tool, path, hint))
    return out


def normalize_path(text: str) -> str:
    """Trim a typed path; spell %LOCALAPPDATA% / %USERPROFILE% via `~` (sources.json does
    not expand environment variables, and none is read here)."""
    value = text.strip().strip('"').strip("'").strip()
    value = _LOCALAPPDATA_RE.sub("~/AppData/Local", value)
    value = _HOME_RE.sub("~", value)
    if not value:
        raise ValueError("path must not be empty")
    if any(c in value for c in "\r\n\0"):
        raise ValueError("path must be a single line")
    return value


def build_config(choices: list[Choice], today: date | None = None) -> dict:
    """The sources.json document: every tool listed, skipped ones as `enabled: false`."""
    for c in choices:
        if c.billing not in BILLING_MODES:
            raise ValueError(f"billing must be one of {', '.join(BILLING_MODES)}")
    stamp = (today or date.today()).isoformat()
    return {
        "_comment": (
            f"Generated by `tracker init` on {stamp}. Only usage metadata (timestamps, models, "
            "token counts) is read from these paths. Set enabled to true/false, or billing to "
            "\"subscription\" (flat plan) / \"api\" (pay-as-you-go API key)."
        ),
        "sources": [
            {"name": c.tool, "tool": c.tool, "path": c.path, "enabled": c.enabled, "billing": c.billing}
            for c in choices
        ],
    }


def render_config(config: dict) -> str:
    return json.dumps(config, indent=2, ensure_ascii=False) + "\n"


def write_config(path: Path, text: str, *, force: bool) -> None:
    """Create `path`; replace an existing file only with `force` (atomically)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if force:
        fsutil.atomic_write_text(path, text)
        return
    # "x" fails if the file appeared meanwhile, so an existing config is never clobbered
    with open(path, "x", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
